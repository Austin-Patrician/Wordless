/**
 * 主进程侧的设计画布预算。
 *
 * 与渲染层的 `renderer/features/design/budgets.ts` 分开,理由是**它们的主人和失败模式都不同**:
 *
 * - 渲染层那份管位图与 LRU(占用的是渲染进程的内存)
 * - 这份管离屏视图与子进程(占用的是**真实渲染进程**与系统资源)
 *
 * P0 时我把它们都放在渲染层那份里,结果是主进程必须反向 import 渲染层的模块 —— 分层是反的。
 * 更实际的问题是:渲染层从不读这几个数(实测确认),它们放在那里只会让"谁拥有这个资源"
 * 这件事变得模糊。
 *
 * 本文件不 import React、不 import Electron。
 */

export const DESIGN_RASTER_BUDGETS = {
  /**
   * 同时存在的离屏视图数,也是光栅池的并发数。
   *
   * 每个离屏视图是一个**真实渲染进程**:不限并发的话,打开一份 40 帧的设计会一次拉起
   * 40 个进程。两者必须一致 —— 池的并发高于窗口数时不会出错,但会退化成排队等窗口。
   */
  rasterConcurrency: 2,
  /** 单帧光栅化超时。超时按失败上报,由帧的状态机进 `failed`(可见的错误态,不是空白)。 */
  rasterTimeoutMs: 5_000,
  /** 构建超时(仅 `mode: "built"`,P7)。 */
  buildTimeoutMs: 120_000,
} as const;
